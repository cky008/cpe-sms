import fs from "node:fs";
import path from "node:path";

interface LocaleMeta {
  code: string;
  name: string;
}

function flattenKeys(obj: Record<string, unknown>, prefix = ""): Record<string, string> {
  const result: Record<string, string> = {};
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith("_")) continue;
    const fullKey = prefix ? `${prefix}.${k}` : k;
    if (typeof v === "string") {
      result[fullKey] = v;
    } else if (v && typeof v === "object" && !Array.isArray(v)) {
      Object.assign(result, flattenKeys(v as Record<string, unknown>, fullKey));
    }
  }
  return result;
}

export function buildLocales(): void {
  const root = process.cwd();
  const localesDir = path.resolve(root, "locales");
  const targetFile = path.resolve(root, "src", "web", "client", "locales.generated.ts");
  const publicLocalesDir = path.resolve(root, "src", "web", "public", "locales");
  const distLocalesDir = path.resolve(root, "dist", "web", "public", "locales");

  if (!fs.existsSync(localesDir)) {
    throw new Error(`locales directory not found at ${localesDir}`);
  }

  const files = fs
    .readdirSync(localesDir)
    .filter((f) => f.endsWith(".json"))
    .sort();

  const supported: LocaleMeta[] = [];
  const rawDict: Record<string, Record<string, unknown>> = {};
  const flatDict: Record<string, Record<string, string>> = {};

  for (const file of files) {
    const filePath = path.join(localesDir, file);
    const content = JSON.parse(fs.readFileSync(filePath, "utf8")) as Record<string, unknown>;
    const defaultCode = file.replace(/\.json$/, "");
    const meta = (content._meta as { name?: string; code?: string } | undefined) ?? {};
    const code = meta.code || defaultCode;
    const name = meta.name || code;

    supported.push({ code, name });
    rawDict[code] = content;
    flatDict[code] = flattenKeys(content);
  }

  // Ensure default locale exists
  if (!supported.some((s) => s.code === "zh-CN")) {
    throw new Error("Missing default locale zh-CN in locales/");
  }

  // Generate TypeScript code
  const codeContent = `// Auto-generated by scripts/build-locales.ts. Do not edit directly.

export interface LocaleOption {
  code: string;
  name: string;
}

export const SUPPORTED_LOCALES: ReadonlyArray<LocaleOption> = ${JSON.stringify(supported, null, 2)};

export const DEFAULT_LOCALE = "zh-CN";

export const FLATTENED_LOCALES: Record<string, Record<string, string>> = ${JSON.stringify(flatDict, null, 2)};
`;

  fs.writeFileSync(targetFile, codeContent, "utf8");

  // Sync to public directories for offline serving
  for (const outDir of [publicLocalesDir, distLocalesDir]) {
    fs.mkdirSync(outDir, { recursive: true });
    for (const file of files) {
      fs.copyFileSync(path.join(localesDir, file), path.join(outDir, file));
    }
  }

  console.log(
    `✅ Built ${supported.length} locales (${supported.map((s) => s.code).join(", ")}) -> ${path.relative(root, targetFile)}`
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  buildLocales();
}
